from collections.abc import Callable, Sequence
from typing import Protocol

from study_supporter.application.contracts.learning import ProgressEvent

ProgressCallback = Callable[[ProgressEvent], None]


class DocumentRepositoryPort(Protocol):
    def create(self, user_id: str, filename: str, file_hash: str | None = None) -> dict: ...
    def get(self, user_id: str, document_id: int) -> dict: ...
    def latest(self, user_id: str) -> dict | None: ...
    def find_hash(self, user_id: str, file_hash: str) -> dict | None: ...
    def update(self, user_id: str, document_id: int, **values) -> None: ...


class ProgressRepositoryPort(Protocol):
    def record_attempt(
        self,
        user_id: str,
        topic: str,
        question: str,
        is_correct: bool,
        document_id: int | None = None,
    ) -> None: ...
    def get_summary(self, user_id: str) -> dict: ...


class NoteRepositoryPort(Protocol):
    def save_note(self, user_id: str, note: str) -> str: ...
    def search_notes(self, user_id: str, query: str, top_k: int = 3) -> list[str]: ...


class ParserPort(Protocol):
    def parse(self, filename: str, content: bytes, on_progress: Callable | None = None): ...


class EmbeddingProviderPort(Protocol):
    @property
    def model_id(self) -> str: ...
    @property
    def dimension(self) -> int: ...
    def embed(self, texts: Sequence[str], task_type: str) -> list[list[float]]: ...


class VectorDocumentPort(Protocol):
    def count(self) -> int: ...
    def add_chunks(self, chunks: Sequence, embeddings: list[list[float]]) -> None: ...
    def load_all_chunks(self) -> Sequence: ...
